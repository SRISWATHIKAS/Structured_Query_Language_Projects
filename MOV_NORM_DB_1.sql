-- 28. List actors who have worked in more than 3 languages.
SELECT A.ACT_NAME , COUNT( DISTINCT L.LANG) AS TOTAL_LANGUAGES
FROM MOV_NORM M 
INNER JOIN ACT_MAST A ON A.ACT_ID = M.ACT_ID
INNER JOIN LANG_MAST L ON L.LANG_ID = M.LANG_ID
GROUP BY A.ACT_NAME
HAVING COUNT( DISTINCT L.LANG) > 3
ORDER BY TOTAL_LANGUAGES DESC ;
