-- D. GROUP BY + HAVING
-- 24. List languages that have more than 100 movies.
SELECT L.LANG , COUNT(*) AS LANGUAGES_MORETHAN_100
FROM MOV_NORM M 
INNER JOIN LANG_MAST AS L ON L.LANG_ID = M.LANG_ID
GROUP BY L.LANG
HAVING COUNT(*) > 100;

-- 25. List actors who acted in more than 10 movies.
SELECT A.ACT_NAME , COUNT(*) AS ACTOR_MORETHAN_10
FROM MOV_NORM M 
INNER JOIN ACT_MAST A ON A.ACT_ID = M.ACT_ID
GROUP BY A.ACT_NAME
HAVING COUNT(*) > 10;

-- 26. List directors who directed at least 5 movies.
